export interface DeliveryOption {
  method: DeliveryMethod;
  wilayaId: number;
  price: number;
  estimatedDays: string;
  label: string;
  description: string;
}

export function getWilayaById(id: number): Wilaya | undefined {
  return wilayas.find((w) => w.id === id);
}

export function getCommunesByWilaya(wilayaId: number): Commune[] {
  const wilaya = getWilayaById(wilayaId);
  return wilaya?.communes ?? [];
}

export function getDeliveryOptions(wilayaId: number): DeliveryOption[] {
  const wilaya = getWilayaById(wilayaId);
  if (!wilaya) return [];

  return (Object.keys(deliveryMethods) as DeliveryMethod[]).map((method) => ({
    method,
    wilayaId,
    price: wilaya.deliveryPrices[method],
    estimatedDays: deliveryMethods[method].estimatedDays,
    label: deliveryMethods[method].label,
    description: deliveryMethods[method].description,
  }));
}

export function calculateDeliveryPrice(wilayaId: number, method: DeliveryMethod): number {
  const wilaya = getWilayaById(wilayaId);
  if (!wilaya) return 0;
  return wilaya.deliveryPrices[method];
}